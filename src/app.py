def split_reviews(transcript):
    """
    Robust Review Segmentation Engine
    1. Splits using advanced regex (handles casing, punctuation, spelling variants)
    2. Fallback: Splits long transcripts into sentence-chunks if no 'next review' found
    3. Cleanup: Removes short fragments and noise
    """
    if not transcript or not transcript.strip():
        print("DEBUG: Empty transcript received.")
        return []

    # --- PHASE 1: REGEX-BASED SPLITTING ---
    # Handles: "next review", "next-review", "NextReview", "next  review.", etc.
    pattern = r'(?i)\.?\s*next[\s\-_]*review[\s\.\!\?\:]*'
    
    segments = re.split(pattern, transcript)
    
    # Initial cleaning
    pre_cleaned = [s.strip() for s in segments if len(s.strip().split()) >= 5]
    
    # --- PHASE 2: FALLBACK LOGIC ---
    final_reviews = []
    if len(pre_cleaned) <= 1 and pre_cleaned:
        full_text = pre_cleaned[0]
        sentences = re.split(r'(?<=[.!?])\s+', full_text)
        if len(sentences) > 3:
            for i in range(0, len(sentences), 3):
                chunk = " ".join(sentences[i:i+3]).strip()
                if chunk: final_reviews.append(chunk)
        else:
            final_reviews = pre_cleaned
    else:
        final_reviews = pre_cleaned

    # --- PHASE 3: FINAL POLISH ---
    final_output = []
    for review in final_reviews:
        review = re.sub(r'^[^\w\s]+|[^\w\s]+$', '', review).strip()
        if len(review.split()) >= 5:
            final_output.append(review)

    print(f"DEBUG: Splitting completed. Reviews detected: {len(final_output)}")
    return final_output

def analyze_reviews_batch(segments, vectorizer, model):
    """
    Analyze a list of review segments in batch for efficiency.
    Requirement 4 & 7
    """
    if not segments:
        return []
    
    # 1. Preprocess each segment using existing logic
    processed_segments = [preprocess_text(seg) for seg in segments]
    
    # 2. Transform using existing TF-IDF vectorizer (Requirement 7 - Avoid loops)
    features = vectorizer.transform(processed_segments)
    
    # 3. Predict sentiment using existing model
    predictions = model.predict(features)
    
    # 4. Compute confidence score using predict_proba() (Requirement 4)
    probabilities = model.predict_proba(features)
    
    results = []
    for i, seg in enumerate(segments):
        pred_label = predictions[i]
        prob_dist = probabilities[i]
        
        # Find index of predicted label to get confidence
        pred_idx = np.where(model.classes_ == pred_label)[0][0]
        confidence = prob_dist[pred_idx]
        
        results.append({
            'text': seg,
            'sentiment': pred_label,
            'confidence': confidence
        })
        
    return results

