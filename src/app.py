def normalize_audio(audio_file):
    """
    Robust audio normalization for consistent transcription.
    """
    debug_log = []
    try:
        audio_file.seek(0)
        debug_log.append(f"Reading file: {getattr(audio_file, 'name', 'Uploaded File')}")
        
        audio = AudioSegment.from_file(audio_file)
        debug_log.append(f"Original: {audio.frame_rate}Hz, {audio.channels} channels")
        
        # Standardize for Speech Engines
        audio = audio.set_frame_rate(16000).set_channels(1).set_sample_width(2)
        debug_log.append(f"Normalized: 16000Hz, Mono, 16-bit")
        
        normalized_io = io.BytesIO()
        audio.export(normalized_io, format="wav")
        normalized_io.seek(0)
        return normalized_io, debug_log
    except Exception as e:
        return None, debug_log + [f"Normalization Error: {str(e)}"]

def transcribe_audio_whisper(audio_io):
    """
    Transcribe using OpenAI Whisper (Local, robust, no API keys).
    """
    try:
        model = load_whisper_model()
        if model is None:
            return None, "Whisper model not available."
            
        # Save to temp file because Whisper works best with paths
        with tempfile.NamedTemporaryFile(delete=False, suffix=".wav") as tmp:
            tmp.write(audio_io.read())
            tmp_path = tmp.name
            
        result = model.transcribe(tmp_path, fp16=False)
        os.unlink(tmp_path)
        return result["text"].strip(), None
    except Exception as e:
        return None, f"Whisper failed: {str(e)}"

def transcribe_audio_google(audio_io):
    """
    Fallback: Transcribe using Google Recognition.
    """
    recognizer = sr.Recognizer()
    try:
        audio_io.seek(0)
        with sr.AudioFile(audio_io) as source:
            recognizer.adjust_for_ambient_noise(source, duration=0.5)
            audio_data = recognizer.record(source)
            text = recognizer.recognize_google(audio_data)
            return text.strip(), None
    except sr.UnknownValueError:
        return "", "Google: No speech detected."
    except sr.RequestError as e:
        return None, f"Google API error: {str(e)}"
    except Exception as e:
        return None, f"Google failed: {str(e)}"

def audio_to_text(audio_file):
    """
    Main Orchestrator for Audio Transcription.
    Features: Normalization, Whisper Engine, Google Fallback.
    """
    status_placeholder = st.empty()
    
    # 1. Normalization
    status_placeholder.info("⚙️ Normalizing audio...")
    normalized_io, debug_log = normalize_audio(audio_file)
    
    if not normalized_io:
        return f"ERROR: Normalization failed."

    # 2. Primary Engine: Whisper
    status_placeholder.info("🎙️ Transcribing with Whisper (Local)...")
    transcript, error = transcribe_audio_whisper(normalized_io)
    
    if transcript:
        status_placeholder.empty()
        return transcript
        
    # 3. Fallback Engine: Google
    status_placeholder.warning("⚠️ Whisper failed, trying Google Fallback...")
    transcript, error = transcribe_audio_google(normalized_io)
    
    if transcript:
        status_placeholder.empty()
        return transcript
        
    status_placeholder.empty()
    if error == "Google: No speech detected.":
        return "ERROR: No text detected in audio. Please ensure you are speaking clearly."
        
    return f"ERROR: Transcription failed. Details: {error}"

