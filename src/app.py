def extract_audio_from_video(video_file):
    """
    Extract audio from uploaded video file using MoviePy.
    Saves and returns path to a temp WAV file (Mono, 16kHz).
    Requirement: Step 2
    """
    try:
        # Create temp file for the uploaded video to be readable by moviepy
        with tempfile.NamedTemporaryFile(delete=False, suffix='.mp4') as tmp_video:
            tmp_video.write(video_file.getbuffer())
            tmp_video_path = tmp_video.name
            
        # Create temp file for output audio (Requirement: Step 2)
        tmp_audio_path = os.path.join(tempfile.gettempdir(), f"temp_audio_{int(time.time())}.wav")
        
        # Load the video file
        video = VideoFileClip(tmp_video_path)
        
        if video.audio is None:
            video.close()
            os.unlink(tmp_video_path)
            return "ERROR: No audio track found in video."
            
        # Step 2: Convert the extracted audio into WAV format (mono, 16kHz)
        # Using ffmpeg_params specifically for mono and 16k
        video.audio.write_audiofile(
            tmp_audio_path, 
            fps=16000, 
            nbytes=2, 
            codec='pcm_s16le', 
            ffmpeg_params=["-ac", "1"],
            logger=None
        )
        
        video.close()
        # Clean up video temp file as per Step 8
        if os.path.exists(tmp_video_path):
            os.unlink(tmp_video_path)
        
        return tmp_audio_path
        
    except Exception as e:
        return f"ERROR: {str(e)}"

